import java.nio.charset.Charset;
import java.nio.charset.MalformedInputException;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;

public class SpecMethodLogicAppender {

    public static void main(String[] args) throws Exception {
        Args a = Args.parse(args);
        if (!a.ok()) { Args.usage(); return; }

        Path specPath = Paths.get(a.specFile).toAbsolutePath().normalize();
        if (!Files.exists(specPath)) {
            System.err.println("[ERROR] No such spec file: " + specPath);
            return;
        }

        Path logicPath = Paths.get(a.logicFile).toAbsolutePath().normalize();
        if (!Files.exists(logicPath)) {
            System.err.println("[ERROR] No such logic file: " + logicPath);
            return;
        }

        // 🔹 Read both files with UTF-8 first, then fall back to system charset if needed
        String json  = readTextBestEffort(specPath);
        String logic = readTextBestEffort(logicPath).trim();

        if (logic.isEmpty()) {
            System.err.println("[WARN] Logic file is empty, nothing to do.");
            return;
        }

        String logicBlock = buildNewMethodLogicSpecBlock(logic);

        // We assume spec was generated by ClassToSpecJsonFile and has no existing newMethodLogicSpec.
        // Insert before the final "}\n"
        int idx = json.lastIndexOf("\n}\n");
        if (idx < 0) {
            // Fallback: last '}' position
            idx = json.lastIndexOf('}');
            if (idx < 0) {
                throw new IllegalStateException("Spec JSON does not look valid / no closing brace found.");
            }
            String prefix = json.substring(0, idx).trim();
            String suffix = json.substring(idx);
            json = prefix + ",\n" + logicBlock + "\n" + suffix;
        } else {
            String prefix = json.substring(0, idx).trim();
            String suffix = json.substring(idx); // "\n}\n"
            json = prefix + ",\n" + logicBlock + suffix;
        }

        // Always overwrite the same spec file (now normalized as UTF-8)
        Files.writeString(specPath, json, StandardCharsets.UTF_8);
        System.out.println("[OK] Updated spec with newMethodLogicSpec: " + specPath.toAbsolutePath());
    }

    // ---------- robust text reading helper ----------
    private static String readTextBestEffort(Path path) throws Exception {
        try {
            // first try UTF-8
            return Files.readString(path, StandardCharsets.UTF_8);
        } catch (MalformedInputException e) {
            // fall back to system default charset (e.g. Windows-1251 / 1252)
            Charset fallback = Charset.defaultCharset();
            System.out.println("[WARN] File " + path + " is not valid UTF-8. "
                    + "Falling back to system charset: " + fallback);
            byte[] bytes = Files.readAllBytes(path);
            return new String(bytes, fallback);
        }
    }

    // ---------- Args ----------
    static final class Args {
        String specFile;   // required
        String logicFile;  // required

        static Args parse(String[] av) {
            Args a = new Args();
            for (int i = 0; i < av.length; i++) {
                switch (av[i]) {
                    case "--specFile" -> {
                        if (i + 1 < av.length) a.specFile = av[++i];
                    }
                    case "--logicFile" -> {
                        if (i + 1 < av.length) a.logicFile = av[++i];
                    }
                }
            }
            return a;
        }

        boolean ok() { return specFile != null && logicFile != null; }

        static void usage() {
            System.out.println("""
                SpecMethodLogicAppender - add newMethodLogicSpec to an existing *_spec.json,
                loading the logic from a text file.

                Usage:
                  java SpecMethodLogicAppender --specFile Dori_spec.json \\
                      --logicFile logic.txt

                Where:
                  - --specFile   points to an existing *_spec.json produced by ClassToSpecJsonFile
                  - --logicFile  is a text file whose entire contents are a natural-language
                                  description of ONE new method you want OpenAI to generate.

                Notes:
                  - The tool first tries to read files as UTF-8; if that fails, it falls back
                    to the system default charset.
                  - The logic text is stored under the key "logic_1" inside newMethodLogicSpec.
                  - The spec file is modified in-place (overwritten, as UTF-8).
            """);
        }
    }

    // ---------- Build newMethodLogicSpec from a single logic string ----------
    static String buildNewMethodLogicSpecBlock(String logic) {
        StringBuilder sb = new StringBuilder();
        sb.append("  \"newMethodLogicSpec\": {");
        sb.append("\n    ")
          .append(js("logic_1"))
          .append(": ")
          .append(js(logic));
        sb.append("\n  }");
        return sb.toString();
    }

    static String js(String s) {
        if (s == null) return "null";
        return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
    }
}
